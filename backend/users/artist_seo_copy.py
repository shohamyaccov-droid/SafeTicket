def apply_artist_bottom_seo_texts(*, artist_model=None, stdout=None):
    """
    Fill Artist.bottom_seo_text for known headliners.
    Missing artists are skipped with a warning (never raise).
    """
    if artist_model is None:
        from users.models import Artist as artist_model

    updated = []
    skipped = []
    for row in ARTIST_BOTTOM_SEO_TEXTS:
        qs = artist_model.objects.filter(Q(name__in=row['names']) | Q(slug__in=row['slugs']))
        count = qs.update(bottom_seo_text=row['text'])
        if count:
            updated.append((row['label'], count))
            continue
        msg = f'Artist not found for bottom SEO copy: {row["label"]} (slugs={list(row["slugs"])})'
        logger.warning(msg)
        if stdout is not None:
            stdout.write(msg)
        skipped.append(row['label'])
    return updated, skipped
